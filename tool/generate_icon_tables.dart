// Writes the two tables of Material icons the editor uses, from the Flutter
// SDK's own list of them:
//
//   dart run tool/generate_icon_tables.dart <path to material/icons.dart>
//
// The names go to the domain, which is plain Dart, and the IconData values to
// the presentation layer. The rounded and sharp variants are left out: the
// filled and outlined ones are what a screen design needs.

import 'dart:io';

final RegExp _icon = RegExp(
  r'^\s+static const IconData ([a-z][a-z0-9_]*) = IconData\(',
  multiLine: true,
);
final RegExp _otherStyle = RegExp(r'_(rounded|sharp)$');

const String _namesPath =
    'lib/features/editor/domain/definitions/icon_names.dart';
const String _tablePath =
    'lib/features/editor/presentation/preview/icon_table.dart';
const String _header =
    '// GENERATED by tool/generate_icon_tables.dart: do not edit by hand.\n';

void main(List<String> arguments) {
  if (arguments.isEmpty) {
    stderr.writeln('Pass the path of flutter/lib/src/material/icons.dart');
    exitCode = 64;
    return;
  }
  final source = File(arguments.first).readAsStringSync();
  final names =
      _icon
          .allMatches(source)
          .map((match) => match.group(1) ?? '')
          .where((name) => !_otherStyle.hasMatch(name))
          .toSet()
          .toList()
        ..sort();
  File(_namesPath).writeAsStringSync(_namesFile(names));
  File(_tablePath).writeAsStringSync(_tableFile(names));
  stdout.writeln('Wrote ${names.length} icons');
}

String _namesFile(List<String> names) {
  final lines = names.map((name) => "  '$name',").join('\n');
  return '$_header\n'
      '/// Names of the Material icons a screen can use, in alphabetical order.\n'
      'const List<String> iconNames = [\n$lines\n];\n';
}

String _tableFile(List<String> names) {
  final lines = names.map((name) => "  '$name': Icons.$name,").join('\n');
  return '$_header\n'
      "import 'package:flutter/material.dart';\n\n"
      '/// Icons addressable by the names in iconOptions.\n'
      'const Map<String, IconData> iconsByName = {\n$lines\n};\n';
}
