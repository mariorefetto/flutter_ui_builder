import 'package:flutter_ui_builder/features/editor/domain/entities/generated_file.dart';
import 'package:flutter_ui_builder/features/editor/domain/entities/prop_schema.dart';
import 'package:flutter_ui_builder/features/editor/domain/services/code_formatter.dart';
import 'package:flutter_ui_builder/features/editor/domain/services/component_binding.dart';
import 'package:flutter_ui_builder/features/editor/domain/services/node_queries.dart';
import 'package:flutter_ui_builder/features/editor/domain/services/screen_editor.dart';

/// First line of a generated file's marker. Export refuses to overwrite files
/// that lack it, so hand written code is never replaced.
const String generatedFileMarker = 'GENERATED CODE - DO NOT MODIFY BY HAND.';

/// The file the theme of the app is written to.
const String themeFileName = 'app_theme.g.dart';

const String _materialLibrary = 'package:flutter/material.dart';

/// Turns a document into a formatted Dart file with one StatelessWidget.
class DocumentCodeGenerator {
  const DocumentCodeGenerator(this._registry, this._formatter);

  final WidgetRegistry _registry;
  final CodeFormatter _formatter;

  Either<Failure, GeneratedFile> generate(EditorDocument document) {
    final className = document.component
        ? componentClassName(document.name)
        : screenClassName(document.name);
    final source = _source(document, className);
    try {
      return Right(
        GeneratedFile(
          fileName: document.component
              ? componentFileName(document.name)
              : screenFileName(document.name),
          content: _formatter.format(source),
        ),
      );
    } on FormatException catch (e) {
      return Left(CodeGenerationFailure(e.message));
    }
  }

  /// One file for each screen and component of the project, in project order.
  Either<Failure, List<GeneratedFile>> generateAll(EditorDocument document) {
    final files = <GeneratedFile>[];
    for (final entry in const ScreenEditor().entriesOf(document)) {
      final result = generate(
        EditorDocument(
          name: entry.name,
          root: entry.root,
          component: entry.component,
          screens: document.screens,
        ),
      );
      if (result.isLeft()) return result.map((_) => const []);
      result.map(files.add);
    }
    // The theme is written out only when it differs from Flutter's own.
    if (!document.theme.isDefault) files.add(generateTheme(document));
    return Right(files);
  }

  /// The theme of the app as a file with two functions, `buildAppTheme` and
  /// `buildAppDarkTheme`, for `MaterialApp(theme:, darkTheme:)`.
  GeneratedFile generateTheme(EditorDocument document) {
    final light = dartArguments(themeArguments(document.theme));
    final dark = dartArguments(themeArguments(document.theme, dark: true));
    final source =
        '''
// $generatedFileMarker
// Generated by Flutter UI Builder from the theme of the project.
// ignore_for_file: type=lint

import 'package:flutter/material.dart';

/// The light theme of the app.
ThemeData buildAppTheme() {
  return ThemeData($light);
}

/// The dark theme of the app. Use both as
/// `MaterialApp(theme: buildAppTheme(), darkTheme: buildAppDarkTheme())`.
ThemeData buildAppDarkTheme() {
  return ThemeData($dark);
}
''';
    return GeneratedFile(
      fileName: themeFileName,
      content: _formatter.format(source),
    );
  }

  String _source(EditorDocument document, String className) {
    final params = document.component
        ? document.params
        : const <ComponentParam>[];
    final standIns = standInsFor(document.root, params, _literal);
    final body = standIns.apply(_registry.generateCode(standIns.root));
    final imports = _imports(document);
    return '''
// $generatedFileMarker
// Generated by Flutter UI Builder from the document "${_comment(document.name)}".
// ignore_for_file: type=lint, unnecessary_import

$imports

class $className extends StatelessWidget {
  const $className({super.key${_constructorParams(params)}});
${_fields(params)}
  @override
  Widget build(BuildContext context) {
    return $body;
  }
}
''';
  }

  // How a value of a parameter is written in code.
  String _literal(Object value, PropType type) => switch (value) {
    final String text => dartString(text),
    final num number when type == PropType.number => dartDouble(
      number.toDouble(),
    ),
    final int color => dartColor(color),
    _ => '$value',
  };

  // The named parameters of a component's constructor, each with its default.
  String _constructorParams(List<ComponentParam> params) => [
    for (final param in params)
      ', this.${param.name} = ${_literal(param.defaultValue, param.type)}',
  ].join();

  String _fields(List<ComponentParam> params) => params.isEmpty
      ? ''
      : '\n${[for (final param in params) '  final ${_dartType(param.type)} ${param.name};'].join('\n')}\n';

  String _dartType(PropType type) => switch (type) {
    PropType.string => 'String',
    PropType.number => 'double',
    _ => 'Color',
  };

  String _imports(EditorDocument document) {
    final libraries = {
      _materialLibrary,
      ..._registry.importsFor(document.root),
    }.toList()..sort();
    // The screens it opens and the components it shows sit in files of their
    // own, next to it.
    final siblings = {
      for (final name in document.root.navigationTargets())
        if (screenClassName(name) != screenClassName(document.name))
          screenFileName(name),
      for (final name in document.root.componentTargets())
        if (componentClassName(name) != componentClassName(document.name))
          componentFileName(name),
    }.toList()..sort();
    return [
      ...libraries.map((library) => "import '$library';"),
      ...siblings.map((file) => "import '$file';"),
    ].join('\n');
  }

  // Keeps a document name from breaking out of the one line comment.
  String _comment(String text) => text.replaceAll(RegExp(r'[\r\n]+'), ' ');
}
